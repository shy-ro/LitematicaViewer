namespace LitematicaViewer.Previewer;

// 转视角的手势。自由视角与展台只差这一件事，所以它是同一个适配器上的一个开关，而不是两个适配器：
// 订阅哪些事件、捕获、线程、钉不住时的降级、失活时怎么收尾，两边完全一样，
// 分成两份之后改一处就会漏一处——而漏掉的那一处表现是「某个模式下偶尔卡住」。
public enum LookGesture
{
    // 指针一动就转，并把光标钉在视口中心后藏起来。手可以一直朝一个方向划，撞不到屏幕边。
    FollowPointer,

    // 按住左键拖才转，光标不钉不藏。拖动是一次有头有尾的手势，而要拖就得看得见光标。
    DragPrimaryButton,
}
